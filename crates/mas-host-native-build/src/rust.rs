use super::{run, write, Result};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub(super) fn build(
    source: &Path,
    directory: &Path,
    executable: &Path,
    sdk_root: &Path,
    handler: &str,
    index: usize,
) -> Result<()> {
    // JSON strings are valid TOML basic strings for these validated local paths.
    let sdk = serde_json::to_string(&sdk_root.join("sdk/rust")).map_err(|e| e.to_string())?;
    let manifest=format!("[package]\nname = \"mas-generated-worker-{index}\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n\n[dependencies]\nmas-host-sdk = {{ path = {sdk} }}\n\n[[bin]]\nname = \"worker-{index}\"\npath = \"main.rs\"\n");
    write(directory.join("Cargo.toml"), manifest)?;
    let main=format!("// Generated by MAS host; do not edit.\n#[path = {source:?}]\nmod application;\nfn main() {{\n    if let Err(error) = mas_host_sdk::serve({handler:?}, application::{handler}) {{\n        eprintln!(\"{{error}}\");\n        std::process::exit(1);\n    }}\n}}\n");
    write(directory.join("main.rs"), main)?;
    let target: PathBuf = directory
        .parent()
        .ok_or("missing build parent")?
        .join("rust-target");
    let lock = directory.join("Cargo.lock");
    let existing_lock = lock.exists();
    if !existing_lock {
        // The SDK graph is a subset of the distribution workspace. Seed its
        // resolved dependency versions before Cargo adds this generated package.
        fs::copy(sdk_root.join("Cargo.lock"), &lock)
            .map_err(|e| format!("SDK distribution must include Cargo.lock: {e}"))?;
    }
    let mut command = Command::new("cargo");
    command
        .arg("build")
        .arg("--manifest-path")
        .arg(directory.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target);
    if existing_lock {
        command.arg("--locked");
    }
    run(&mut command)?;
    fs::copy(target.join(format!("debug/worker-{index}")), executable)
        .map_err(|e| e.to_string())?;
    Ok(())
}
