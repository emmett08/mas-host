//! Generated native worker entrypoints. Application source remains wrapper-free.
use serde_json::{json, Value};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

type Result<T> = std::result::Result<T, String>;
fn field<'a>(value: &'a Value, name: &str) -> Result<&'a str> {
    value[name]
        .as_str()
        .ok_or_else(|| format!("agent {name} must be a string"))
}
fn identifier(name: &str) -> bool {
    let mut chars = name.bytes();
    matches!(chars.next(), Some(b'a'..=b'z' | b'A'..=b'Z' | b'_'))
        && chars.all(|c| c.is_ascii_alphanumeric() || c == b'_')
}
fn write(path: impl AsRef<Path>, content: impl AsRef<[u8]>) -> Result<()> {
    fs::write(path.as_ref(), content).map_err(|e| format!("{}: {e}", path.as_ref().display()))
}
fn run(command: &mut Command) -> Result<()> {
    let output = command
        .output()
        .map_err(|e| format!("cannot run {command:?}: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "native application build failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(())
}
fn cpp_path(path: &Path) -> Result<&str> {
    let text = path.to_str().ok_or("C++ source paths must be UTF-8")?;
    if text.contains(['"', '\\', '\n', '\r']) {
        return Err("C++ source paths cannot contain quotes, backslashes or newlines".into());
    }
    Ok(text)
}

/// Build only Rust and C++ agents; the caller combines the returned records with Go.
/// `sdk_root` is the MAS host distribution root; `agents` is the configuration array.
pub fn build(project: &Path, out: &Path, sdk_root: &Path, agents: &Value) -> Result<Vec<Value>> {
    let project = project.canonicalize().map_err(|e| e.to_string())?;
    fs::create_dir_all(out).map_err(|e| e.to_string())?;
    let out = out.canonicalize().map_err(|e| e.to_string())?;
    let sdk_root = sdk_root.canonicalize().map_err(|e| e.to_string())?;
    let mut built = Vec::new();
    for (index, agent) in agents
        .as_array()
        .ok_or("agents must be an array")?
        .iter()
        .enumerate()
    {
        let language = field(agent, "language")?;
        if language == "go" {
            continue;
        }
        if !matches!(language, "rust" | "cpp") {
            return Err(format!("unsupported language: {language}"));
        }
        let name = field(agent, "name")?;
        let handler = field(agent, "handler")?;
        if !identifier(handler) {
            return Err(format!(
                "{name}: handler must be a single native function identifier"
            ));
        }
        let source = project
            .join(field(agent, "source")?)
            .canonicalize()
            .map_err(|e| format!("{name} source: {e}"))?;
        if !source.starts_with(&project) || !source.is_file() {
            return Err(format!(
                "{name}: source must be a file inside the application directory"
            ));
        }
        let directory = out.join(format!("native-{index}"));
        fs::create_dir_all(&directory).map_err(|e| e.to_string())?;
        let executable = directory.join("worker");
        match language {
            "rust" => build_rust(&source, &directory, &executable, &sdk_root, handler, index)?,
            "cpp" => build_cpp(&source, &directory, &executable, &sdk_root, handler)?,
            _ => unreachable!(),
        }
        built.push(json!({"name":name,"executable":executable,"handler":handler}));
    }
    Ok(built)
}

fn build_rust(
    source: &Path,
    directory: &Path,
    executable: &Path,
    sdk_root: &Path,
    handler: &str,
    index: usize,
) -> Result<()> {
    // JSON strings are valid TOML basic strings for these validated local paths.
    let sdk = serde_json::to_string(&sdk_root.join("sdk/rust")).map_err(|e| e.to_string())?;
    let manifest=format!("[package]\nname = \"mas-generated-worker-{index}\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n\n[dependencies]\nmas-host-sdk = {{ path = {sdk} }}\n\n[[bin]]\nname = \"worker-{index}\"\npath = \"main.rs\"\n");
    write(directory.join("Cargo.toml"), manifest)?;
    let main=format!("// Generated by MAS host; do not edit.\n#[path = {source:?}]\nmod application;\nfn main() {{\n    if let Err(error) = mas_host_sdk::serve({handler:?}, application::{handler}) {{\n        eprintln!(\"{{error}}\");\n        std::process::exit(1);\n    }}\n}}\n");
    write(directory.join("main.rs"), main)?;
    let target: PathBuf = directory
        .parent()
        .ok_or("missing build parent")?
        .join("rust-target");
    let lock = directory.join("Cargo.lock");
    let existing_lock = lock.exists();
    if !existing_lock {
        // The SDK graph is a subset of the distribution workspace. Seed its
        // resolved dependency versions before Cargo adds this generated package.
        fs::copy(sdk_root.join("Cargo.lock"), &lock)
            .map_err(|e| format!("SDK distribution must include Cargo.lock: {e}"))?;
    }
    let mut command = Command::new("cargo");
    command
        .arg("build")
        .arg("--manifest-path")
        .arg(directory.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target);
    if existing_lock {
        command.arg("--locked");
    }
    run(&mut command)?;
    fs::copy(target.join(format!("debug/worker-{index}")), executable)
        .map_err(|e| e.to_string())?;
    Ok(())
}

fn build_cpp(
    source: &Path,
    directory: &Path,
    executable: &Path,
    sdk_root: &Path,
    handler: &str,
) -> Result<()> {
    let source = cpp_path(source)?;
    let main=format!("// Generated by MAS host; do not edit.\n#include \"mas.hpp\"\n#include \"{source}\"\nint main() {{ return mas::serve(\"{handler}\", {handler}); }}\n");
    write(directory.join("main.cpp"), main)?;
    run(Command::new("c++")
        .arg("-std=c++17")
        .arg("-Wall")
        .arg("-Wextra")
        .arg("-Werror")
        .arg("-pthread")
        .arg("-I")
        .arg(sdk_root.join("sdk/cpp/include"))
        .arg(directory.join("main.cpp"))
        .arg("-o")
        .arg(executable))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn generated_symbols_cannot_inject_source() {
        for name in ["Assess", "assess_invoice", "_handler"] {
            assert!(identifier(name));
        }
        for name in ["", "0entry", "foo::bar", "run();", "a\nb"] {
            assert!(!identifier(name));
        }
    }
    #[test]
    fn cpp_include_rejects_source_delimiters() {
        assert!(cpp_path(Path::new("/project/app.cpp")).is_ok());
        assert!(cpp_path(Path::new("/project/\"inject.cpp")).is_err());
    }
}
