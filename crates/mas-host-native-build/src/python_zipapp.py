"""Build a deterministic worker archive without executing application code."""

import keyword
import os
from pathlib import Path
import stat
import sys
import tempfile
import zipfile


EXCLUDED_DIRECTORIES = {
    "__pycache__", "venv", "build", "dist", "node_modules", "target",
}
MAX_FILES = 4096
MAX_BYTES = 16 * 1024 * 1024
FIXED_TIMESTAMP = (1980, 1, 1, 0, 0, 0)


def snapshot(root, prefix, entries, budget):
    """Copy and syntax-check Python files; directory entries preserve namespaces."""
    def visit(directory):
        for child in sorted(directory.iterdir()):
            if child.name.startswith(".") or child.name in EXCLUDED_DIRECTORIES:
                continue
            if child.is_symlink():
                raise ValueError(f"Python source snapshots do not allow symlinks: {child}")
            if child.is_dir():
                visit(child)
            elif child.suffix == ".py":
                if not child.is_file():
                    raise ValueError(f"Python source must be a regular file: {child}")
                relative = child.relative_to(root).as_posix()
                name = f"{prefix}/{relative}" if prefix else relative
                with child.open("rb") as stream:
                    data = stream.read(MAX_BYTES - budget[1] + 1)
                budget[0] += 1
                budget[1] += len(data)
                if budget[0] > MAX_FILES or budget[1] > MAX_BYTES:
                    raise ValueError("Python source snapshot exceeds 4096 files or 16 MiB")
                compile(data, name, "exec", dont_inherit=True)
                entries[name] = data
                parent = Path(name).parent
                while parent != Path("."):
                    entries[f"{parent.as_posix()}/"] = b""
                    parent = parent.parent

    visit(root)


def module_name(project, source):
    relative = source.relative_to(project)
    if relative.suffix != ".py":
        raise ValueError("Python agent source must have a .py extension")
    components = list(relative.with_suffix("").parts)
    if components[-1] == "__init__":
        components.pop()
    if not components or any(not part.isidentifier() or keyword.iskeyword(part) for part in components):
        raise ValueError("Python agent source must be an importable module path")
    return ".".join(components)


def main():
    if sys.version_info < (3, 11):
        raise ValueError("Python workers require Python 3.11 or newer")
    project, source, output, sdk = map(Path, sys.argv[1:5])
    handler = sys.argv[5]
    # Preserve a virtual environment's invocation path. Resolving its symlink
    # would select the base interpreter and lose that environment's packages.
    interpreter = os.path.abspath(sys.executable)
    if any(character.isspace() for character in interpreter) or "\x00" in interpreter:
        raise ValueError("Python interpreter path must not contain whitespace or NUL")
    shebang = f"#!{interpreter} -I\n".encode()
    if len(shebang) > 127:
        raise ValueError("Python interpreter path is too long for a portable shebang")
    for reserved in ("__main__.py", "mas_host.py", "mas_host"):
        if os.path.lexists(project / reserved):
            raise ValueError(f"Python project path is reserved by the worker: {reserved}")
    if sdk.is_symlink() or not sdk.is_dir() or not (sdk / "__init__.py").is_file():
        raise ValueError("SDK distribution must contain sdk/python/mas_host/__init__.py")
    module = module_name(project, source)
    entries = {}
    budget = [0, 0]
    snapshot(project, "", entries, budget)
    if source.relative_to(project).as_posix() not in entries:
        raise ValueError("Python agent source is inside an excluded source directory")
    snapshot(sdk, "mas_host", entries, budget)
    entries["__main__.py"] = (
        "# Generated by MAS host; do not edit.\n"
        "from mas_host import serve_module\n"
        f"serve_module({handler!r}, {module!r})\n"
    ).encode()
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=output.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(shebang)
            with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_STORED) as archive:
                for name, data in sorted(entries.items()):
                    info = zipfile.ZipInfo(name, FIXED_TIMESTAMP)
                    info.create_system = 3
                    info.compress_type = zipfile.ZIP_STORED
                    mode = (stat.S_IFDIR | 0o755) if name.endswith("/") else (stat.S_IFREG | 0o644)
                    info.external_attr = mode << 16
                    if name.endswith("/"):
                        info.external_attr |= 0x10
                    archive.writestr(info, data)
        temporary.chmod(0o755)
        os.replace(temporary, output)
        temporary = None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


try:
    main()
except (OSError, ValueError, SyntaxError) as error:
    print(f"cannot build Python worker: {error}", file=sys.stderr)
    sys.exit(1)
