use super::{run, write, Result};
use std::path::Path;
use std::process::Command;

pub(super) fn build(
    source: &Path,
    directory: &Path,
    executable: &Path,
    sdk_root: &Path,
    handler: &str,
) -> Result<()> {
    let source = cpp_path(source)?;
    let main=format!("// Generated by MAS host; do not edit.\n#include \"mas.hpp\"\n#include \"{source}\"\nint main() {{ return mas::serve(\"{handler}\", {handler}); }}\n");
    write(directory.join("main.cpp"), main)?;
    run(Command::new("c++")
        .arg("-std=c++17")
        .arg("-Wall")
        .arg("-Wextra")
        .arg("-Werror")
        .arg("-pthread")
        .arg("-I")
        .arg(sdk_root.join("sdk/cpp/include"))
        .arg(directory.join("main.cpp"))
        .arg("-o")
        .arg(executable))
}

fn cpp_path(path: &Path) -> Result<&str> {
    let text = path.to_str().ok_or("C++ source paths must be UTF-8")?;
    if text.contains(['"', '\\', '\n', '\r']) {
        return Err("C++ source paths cannot contain quotes, backslashes or newlines".into());
    }
    Ok(text)
}

